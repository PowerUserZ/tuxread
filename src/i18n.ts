const dictionaries: Record<Lang, Record<Key, string>> = { en, tr };

/** The stored choice wins; otherwise Turkish for a Turkish OS, else English. */
export function pickLang(stored: string | null, osLanguage: string): Lang {
  if (stored === "en" || stored === "tr") return stored;
  return osLanguage.toLowerCase().startsWith("tr") ? "tr" : "en";
}

export function translate(lang: Lang, key: Key, params: Record<string, string | number> = {}) {
  return dictionaries[lang][key].replace(/\{(\w+)\}/g, (whole, name: string) =>
    name in params ? String(params[name]) : whole,
  );
}

export type T = (key: Key, params?: Record<string, string | number>) => string;

export const I18n = createContext<{ lang: Lang; t: T }>({
  lang: "en",
  t: (key, params) => translate("en", key, params),
});

export const useI18n = () => useContext(I18n);
